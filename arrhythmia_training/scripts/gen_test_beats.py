#!/usr/bin/env python3
"""
gen_test_beats.py — 从 DS2 抽真实心拍 → 罐头测试头文件 arrhythmia_test_data.h

为每类(N/S/V/F)挑 int8 tflite 预测正确、置信度最高的若干拍，连同
ECG 窗口 + R-R 特征 + 真值标签 + PC int8 预测类一起写成 C 数组。

上板 arrhythmia_test.cpp 用它验证:
  - NPU(Vela int8) 预测类 == PC int8 预测类  → 训练-部署等价(最紧校验)
  - NPU 预测类 == 真值                        → 真实可用性

用法: python scripts/gen_test_beats.py [--per-class 2]
输出: ../Edgi_Talk_M55_LVGL/applications/arrhythmia_test_data.h
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
NPZ = ROOT / "data" / "processed" / "mitbih.npz"
TFLITE = ROOT / "outputs" / "arrhythmia_int8.tflite"
OUT_H = ROOT.parent / "Edgi_Talk_M55_LVGL" / "applications" / "arrhythmia_test_data.h"
CLASSES = ["N", "S", "V", "F"]   # drop-Q


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-class", type=int, default=2)
    args = ap.parse_args()

    import tensorflow as tf
    d = np.load(NPZ, allow_pickle=True)
    classes_all = [str(c) for c in d["classes"]]
    X, R, y = d["X_test"].astype(np.float32), d["RR_test"].astype(np.float32), d["y_test"]
    if "Q" in classes_all:                       # drop Q 对齐 4 类模型
        q = classes_all.index("Q")
        X, R, y = X[y != q], R[y != q], y[y != q]

    interp = tf.lite.Interpreter(model_path=str(TFLITE))
    interp.allocate_tensors()
    ins = interp.get_input_details()
    out = interp.get_output_details()[0]
    ecg_d = next(t for t in ins if "ecg" in t["name"].lower())
    rr_d = next(t for t in ins if "rr" in t["name"].lower())

    def q8(x, det):
        s, zp = det["quantization"]
        return np.round(x / s + zp).clip(-128, 127).astype(np.int8)

    def predict(i):
        interp.set_tensor(ecg_d["index"], q8(X[i:i+1], ecg_d))
        interp.set_tensor(rr_d["index"], q8(R[i:i+1], rr_d))
        interp.invoke()
        o = interp.get_tensor(out["index"])[0].astype(np.int32)
        return int(o.argmax()), o

    # 逐类挑 int8 预测正确的样本，按 logit 余量排序取置信高的
    picks = []
    for c in range(len(CLASSES)):
        idxs = np.where(y == c)[0]
        scored = []
        for i in idxs[:2000]:                    # 限量扫描足够
            pc, o = predict(i)
            if pc == c:
                margin = int(np.sort(o)[-1] - np.sort(o)[-2])
                scored.append((margin, int(i), pc))
        scored.sort(reverse=True)
        chosen = scored[:args.per_class]
        if not chosen:
            print(f"[warn] 类 {CLASSES[c]} 无 int8 预测正确样本，跳过")
        for _, i, pc in chosen:
            picks.append((i, c, pc))
        print(f"  {CLASSES[c]}: 选 {len(chosen)} 拍")

    n = len(picks)
    lines = [
        "/* AUTO-GENERATED by gen_test_beats.py — DO NOT EDIT */",
        "/* 真实 MIT-BIH DS2 心拍，用于上板 NPU 等价/可用性验证 */",
        "#ifndef __ARRHYTHMIA_TEST_DATA_H__",
        "#define __ARRHYTHMIA_TEST_DATA_H__",
        "",
        f"#define ARR_TEST_N      {n}",
        "#define ARR_TEST_ECG_LEN 256",
        "#define ARR_TEST_RR_DIM  3",
        "",
        "/* 每拍 ECG 窗口 [256]，已 min-max 归一 [0,1] */",
        f"static const float arr_test_ecg[ARR_TEST_N][ARR_TEST_ECG_LEN] = {{",
    ]
    for (i, c, pc) in picks:
        vals = ", ".join(f"{v:.5f}f" for v in X[i, :, 0])
        lines.append(f"  {{ {vals} }},")
    lines += ["};", "",
              "/* 每拍 R-R 特征 [3] = [pre/med, post/med, pre/local] */",
              f"static const float arr_test_rr[ARR_TEST_N][ARR_TEST_RR_DIM] = {{"]
    for (i, c, pc) in picks:
        vals = ", ".join(f"{v:.5f}f" for v in R[i])
        lines.append(f"  {{ {vals} }},")
    lines += ["};", "",
              "/* 真值类别 0=N 1=S 2=V 3=F */",
              "static const int arr_test_true[ARR_TEST_N] = { "
              + ", ".join(str(c) for (_, c, _) in picks) + " };",
              "",
              "/* PC int8 tflite 预测类(上板 NPU 应与之逐拍一致) */",
              "static const int arr_test_ref[ARR_TEST_N] = { "
              + ", ".join(str(pc) for (_, _, pc) in picks) + " };",
              "",
              "#endif /* __ARRHYTHMIA_TEST_DATA_H__ */", ""]

    OUT_H.write_text("\n".join(lines), encoding="utf-8")
    print(f"[ok] 写出 {OUT_H}  ({n} 拍)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
