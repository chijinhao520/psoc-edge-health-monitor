#!/usr/bin/env python3
"""
export_vela.py — Vela 编译 + C 头文件导出（心律不齐模型）

流程：
  1. 找 vela（建议先激活 E:\\vela_env）
  2. vela --accelerator-config ethos-u55-128 … → _vela.tflite
  3. 把 _vela.tflite 转成 C 数组 .h（不依赖 xxd，Windows 可跑）
  4. 输出可直接 #include 的 arrhythmia_model.h

输出:
  outputs/vela/arrhythmia_int8_vela.tflite   Vela 编译后（NPU 可执行）
  outputs/vela/vela_log.txt                  算子兼容性报告（看是否全 NPU 跑）
  outputs/arrhythmia_model.h                 C 头文件（给 arrhythmia_task.c）

E84 配置（同 glucose，BSP 默认）：
  ethos-u55-128 / Ethos_U55_High_End_Embedded / Shared_Sram

用法:
  E:\\vela_env\\Scripts\\activate
  python export_vela.py
  # 或 CPU fallback（不上 NPU）：python export_vela.py --skip-vela
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT_DIR = ROOT / "outputs"
VELA_OUT = OUT_DIR / "vela"


def find_vela(explicit):
    if explicit:
        if Path(explicit).exists():
            return explicit
        sys.exit(f"[err] 指定的 vela 路径不存在: {explicit}")
    found = shutil.which("vela")
    if found:
        return found
    for c in [r"E:\vela_env\Scripts\vela.exe", r"E:\vela_env\bin\vela"]:
        if Path(c).exists():
            return c
    sys.exit("[err] 未找到 vela。先激活 E:\\vela_env\\Scripts\\activate "
             "或 --vela <path>，或 --skip-vela 走 CPU fallback")


def run_vela(vela, tflite_in, out_dir) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [vela,
           "--accelerator-config", "ethos-u55-128",
           "--system-config", "Ethos_U55_High_End_Embedded",
           "--memory-mode", "Shared_Sram",
           "--output-dir", str(out_dir),
           str(tflite_in)]
    print(f"[vela] {' '.join(cmd)}")
    r = subprocess.run(cmd, capture_output=True, text=True)
    (out_dir / "vela_log.txt").write_text(
        r.stdout + "\n--- STDERR ---\n" + r.stderr)
    print(r.stdout)
    if r.returncode != 0:
        print(r.stderr, file=sys.stderr)
        sys.exit(f"[err] vela 编译失败 (exit={r.returncode})，日志 {out_dir/'vela_log.txt'}")
    vt = out_dir / f"{tflite_in.stem}_vela.tflite"
    if not vt.exists():
        cands = list(out_dir.glob("*_vela.tflite"))
        if not cands:
            sys.exit(f"[err] 未找到 _vela.tflite ({out_dir})")
        vt = cands[0]
    return vt


def tflite_to_c_header(tflite, header, var="g_arrhythmia_model"):
    data = tflite.read_bytes()
    n = len(data)
    lines = [
        "/* AUTO-GENERATED by export_vela.py — DO NOT EDIT */",
        f"/* source: {tflite.name} ({n} bytes) */",
        "",
        "#ifndef __MODEL_ARRHYTHMIA_H__",
        "#define __MODEL_ARRHYTHMIA_H__",
        "",
        "#include <stdint.h>",
        "",
        f"#define ARRHYTHMIA_MODEL_LEN  ({n}U)",
        "",
        "/* TFLite Micro 要求 16 字节对齐 */",
        "__attribute__((aligned(16)))",
        f"const uint8_t {var}[ARRHYTHMIA_MODEL_LEN] = {{",
    ]
    for i in range(0, n, 16):
        chunk = data[i:i+16]
        line = "    " + ", ".join(f"0x{b:02x}" for b in chunk)
        if i + 16 < n:
            line += ","
        lines.append(line)
    lines += ["};", "", "#endif /* __MODEL_ARRHYTHMIA_H__ */", ""]
    header.write_text("\n".join(lines))
    print(f"[save] {header} ({n} bytes)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tflite", type=Path, default=OUT_DIR / "arrhythmia_int8.tflite")
    ap.add_argument("--vela", type=str, default=None)
    ap.add_argument("--header", type=Path, default=OUT_DIR / "arrhythmia_model.h")
    ap.add_argument("--skip-vela", action="store_true",
                    help="跳过 vela，直接转 .h（CPU fallback）")
    args = ap.parse_args()

    if not args.tflite.exists():
        sys.exit(f"[err] 找不到 {args.tflite}，先跑 quantize.py")
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    if args.skip_vela:
        print("[skip] 跳过 vela，用原 tflite 生成 .h")
        target = args.tflite
    else:
        vela = find_vela(args.vela)
        print(f"[vela] 使用: {vela}")
        target = run_vela(vela, args.tflite, VELA_OUT)

    tflite_to_c_header(target, args.header)

    print("\n=== 完成 ===")
    print(f"  tflite : {target}")
    print(f"  C 头文件: {args.header}")
    print("\n下一步: 拷 arrhythmia_model.h 到 M55 工程，写 arrhythmia_task.c "
          "走 TFLite Micro 推理（参考 memory 2026-socc-tflite-port-pattern）")


if __name__ == "__main__":
    main()
