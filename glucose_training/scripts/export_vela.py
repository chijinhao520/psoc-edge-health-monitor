#!/usr/bin/env python3
"""
export_vela.py — Vela 编译 + C 头文件导出

流程：
  1. 检查 vela 命令是否可用（建议在 E:\\vela_env 中激活后运行）
  2. vela --accelerator-config ethos-u55-128 ... → _vela.tflite
  3. 用 Python 把 _vela.tflite 转成 C 数组 .h（替代 xxd，Windows 也能跑）
  4. 输出可直接 #include 的 model_glucose.h

输出:
  outputs/vela/glucose_int8_vela.tflite       Vela 编译后模型（NPU 可执行）
  outputs/glucose_model.h                     C 头文件（给 glucose_task.c）
  outputs/vela_report.txt                     Vela 编译日志（含算子兼容性报告）

E84 配置（根据 BSP 默认）：
  accelerator: ethos-u55-128（128 MAC 单元）
  system-config: Ethos_U55_High_End_Embedded
  memory-mode: Shared_Sram（M55 + NPU 共享 SRAM）

用法:
  # Windows: 先激活 vela 环境
  E:\\vela_env\\Scripts\\activate
  python export_vela.py

  # 或显式 vela 路径
  python export_vela.py --vela E:\\vela_env\\Scripts\\vela.exe
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT_DIR = ROOT / "outputs"
VELA_OUT = OUT_DIR / "vela"


def find_vela(explicit: str | None) -> str:
    if explicit:
        if Path(explicit).exists():
            return explicit
        print(f"[err] 指定的 vela 路径不存在: {explicit}")
        sys.exit(1)
    found = shutil.which("vela")
    if found:
        return found
    # 尝试已知路径
    candidates = [
        r"E:\vela_env\Scripts\vela.exe",
        r"E:\vela_env\bin\vela",
    ]
    for c in candidates:
        if Path(c).exists():
            return c
    print(
        "[err] 未找到 vela 命令\n"
        "  - 先激活: E:\\vela_env\\Scripts\\activate\n"
        "  - 或: python export_vela.py --vela E:\\vela_env\\Scripts\\vela.exe"
    )
    sys.exit(1)


def run_vela(vela: str, tflite_in: Path, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [
        vela,
        "--accelerator-config", "ethos-u55-128",
        "--system-config",      "Ethos_U55_High_End_Embedded",
        "--memory-mode",        "Shared_Sram",
        "--output-dir",         str(out_dir),
        str(tflite_in),
    ]
    print(f"[vela] {' '.join(cmd)}")
    result = subprocess.run(cmd, capture_output=True, text=True)
    log = (out_dir / "vela_log.txt")
    log.write_text(result.stdout + "\n--- STDERR ---\n" + result.stderr)
    if result.returncode != 0:
        print(result.stdout)
        print(result.stderr, file=sys.stderr)
        print(f"\n[err] vela 编译失败 (exit={result.returncode})\n日志: {log}")
        sys.exit(result.returncode)
    print(result.stdout)

    # vela 输出文件名 = <stem>_vela.tflite
    vela_tflite = out_dir / f"{tflite_in.stem}_vela.tflite"
    if not vela_tflite.exists():
        # 寻找任意 _vela.tflite
        cands = list(out_dir.glob("*_vela.tflite"))
        if not cands:
            print(f"[err] 未找到 _vela.tflite (查看 {out_dir})")
            sys.exit(1)
        vela_tflite = cands[0]
    return vela_tflite


def tflite_to_c_header(tflite: Path, header: Path, var_name: str = "g_glucose_model") -> None:
    """把 .tflite 文件转成 C 数组头文件（不依赖 xxd）。"""
    data = tflite.read_bytes()
    n = len(data)
    lines = [
        "/* AUTO-GENERATED by export_vela.py — DO NOT EDIT */",
        f"/* source: {tflite.name} ({n} bytes) */",
        "",
        "#ifndef __MODEL_GLUCOSE_H__",
        "#define __MODEL_GLUCOSE_H__",
        "",
        "#include <stdint.h>",
        "",
        f"#define GLUCOSE_MODEL_LEN  ({n}U)",
        "",
        "/* TFLite Micro 要求 16 字节对齐 */",
        f"__attribute__((aligned(16)))",
        f"const uint8_t {var_name}[GLUCOSE_MODEL_LEN] = {{",
    ]
    # 每行 16 字节
    for i in range(0, n, 16):
        chunk = data[i : i + 16]
        line = "    " + ", ".join(f"0x{b:02x}" for b in chunk)
        if i + 16 < n:
            line += ","
        lines.append(line)
    lines.extend([
        "};",
        "",
        "#endif /* __MODEL_GLUCOSE_H__ */",
        "",
    ])
    header.write_text("\n".join(lines))
    print(f"[save] {header} ({n} bytes data, {header.stat().st_size/1024:.1f} KB text)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--tflite",
        type=Path,
        default=OUT_DIR / "glucose_int8.tflite",
        help="量化后 tflite (quantize.py 输出)",
    )
    parser.add_argument(
        "--vela", type=str, default=None,
        help="vela 可执行路径（不指定则自动查找）",
    )
    parser.add_argument(
        "--header",
        type=Path,
        default=OUT_DIR / "glucose_model.h",
        help="输出 C 头文件",
    )
    parser.add_argument(
        "--skip-vela", action="store_true",
        help="跳过 vela 编译，直接把原 tflite 转 .h（CPU fallback 用）",
    )
    args = parser.parse_args()

    if not args.tflite.exists():
        print(f"[err] 找不到 {args.tflite}\n请先运行 quantize.py")
        sys.exit(1)

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    if args.skip_vela:
        print("[skip] 跳过 vela，使用原 tflite 生成 .h")
        target = args.tflite
    else:
        vela = find_vela(args.vela)
        print(f"[vela] 使用: {vela}")
        target = run_vela(vela, args.tflite, VELA_OUT)

    tflite_to_c_header(target, args.header)

    print(f"\n=== 完成 ===")
    print(f"  vela tflite : {target}")
    print(f"  C 头文件    : {args.header}")
    print(f"\n下一步:")
    print(f"  1. 把 {args.header.name} 拷贝到 Edgi_Talk_M55_LVGL/applications/")
    print(f"  2. 修改 glucose_task.c：替换 placeholder 为 TFLite Micro 推理")
    print(f"  3. 重新编译 M55 工程并烧录")


if __name__ == "__main__":
    main()
