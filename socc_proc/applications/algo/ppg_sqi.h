/*
 * PPG 信号质量评估 (SQI) + 生理合理性门控
 *
 * 背景：maxim_heart_rate_and_oxygen_saturation() 的 valid 判据极松 ——
 * 只要在差分信号里找到 >=2 个峰就置 hr_valid=1（见 ppg_process.c Step6），
 * 完全不检查结果是否生理上可能。实测手指没贴稳时会输出
 * "HR: 90 bpm | SpO2: 21%" 且 valid=1，这种帧原样喂进了血糖 CNN / BMR /
 * 健康评分，污染所有下游指标。
 *
 * 本模块提供两道独立的闸门：
 *   ① 当前支持范围检查 —— SpO2/HR 超出配置范围时报告无法可靠测量
 *   ② SQI 评分（软判据）—— 灌注指数 + 峰间隔稳定性 + 峰幅变异，
 *      检出"数值看着正常但信号是伪迹"的情况
 *
 * 无 IMU 的运动伪迹检测方案，PhysioNet/IEEE 文献标准做法。
 * 算法与 5/28 硬件选型决策里的 compute_ppg_sqi() 规划一致。
 * 以下历史调参记录未建立参考仪器真值对照；其“好帧/误杀”判断只作为
 * 当时的调试观察，不能证明测量准确率。当前阈值暂保留，等待实板对照校准。
 */

#ifndef __PPG_SQI_H__
#define __PPG_SQI_H__

#include <stdint.h>
#include <rtthread.h>

/* ======================== 生理范围（硬判据） ======================== */

/* 当前算法支持范围；低于下限不能区分真实低氧与伪迹，按无法可靠测量处理。 */
#define PPG_SPO2_MIN        70
#define PPG_SPO2_MAX        100
/* 静止测量场景的当前输出范围，尚未完成真人对照标定。
 * 超出范围不表示生理上不可能，也不能用通过门控证明结果准确。 */
#define PPG_HR_MIN          40
#define PPG_HR_MAX          150

/* ======================== 手指在位（硬判据，最强） ======================== */

/*
 * IR 直流分量门限。DC 直接反映有多少 LED 光经组织反射回光电二极管，
 * 是"手指在不在"最可靠的判据。
 *
 * 2026-07-16 本机实测（LED 7mA / ADC 4096nA / 18-bit）：
 *   照空气：DC = 3340 ~ 4236
 *   手指贴合：DC = 39854 ~ 45117
 * 两个量程差 10 倍且完全不重叠，取 10000（≈空气基线的 3 倍）留足余量，
 * 兼顾肤色深/贴合轻时 DC 偏低的情况。
 *
 * 注意：DC 高只代表手指在位，不代表波形可用（实测刚贴上时 DC 已达 4 万但
 * 基线仍在漂移），故仍需下面的 SQI 软判据把关。
 */
#define PPG_DC_FINGER_MIN       10000u

/* ======================== SQI 阈值（软判据） ======================== */

/*
 * 灌注指数 PI = AC/DC*100，正常手指 PPG 文献值约 0.5%~5%。
 *
 * 上下限都要判 —— 这是 2026-07-16 实测教训：原设计只判 PI<0.3 为"灌注差"，
 * 但照空气时 DC 极小反使 PI 虚高到 1195~1437%，低阈值方向完全反了、
 * 抓不到"没放手指"。手指刚贴上基线漂移时 PI 也高达 48%。
 * 故 PI 过高同样是信号异常的标志。
 *
 * ★ PI_MAX 30→10（2026-07-16 第二轮，PC 仿真定量）
 *
 * 症状：同一次测量三帧心率 41/104/133 剧烈跳动，而 SQI 打满分放行。
 * 定位手段：把本文件与 ppg_process.c 的算法在 PC 上逐行复刻（纯数学、
 * 零硬件依赖），喂合成 PPG 波形，逐个引入真实系统的畸变来复现症状。
 *
 * 历史合成波形实验在所用模型下复现了运动伪迹导致的漏峰和偏低心率。
 * 这些实验不能排除真实 FIFO 丢样、调度延迟、ADC 饱和或其他硬件问题；
 * 当前采集链需另外核验连续性，真人精度需独立参考仪器验证。
 *
 * 为什么 PI 是那个判据：伪迹帧的 PI 被基线漂移抬高，与干净帧不重叠 ——
 *   干净帧      PI ≈ 3.5~4.1%   HR 正确
 *   伪迹 4×     PI ≈ 22~27%     HR 错(44~88)，而 score 仍 100 → 原样放行
 * 用户实测 PI 在 2.3%~27.4% 之间乱跳，上界正落在"伪迹 4×"这一档，吻合。
 *
 * 阈值扫描（60 帧测试集，两套独立合成模型均复现同一结论）：
 *   PI_MAX=30(原) → 漏网错帧 8~12 帧，误杀好帧 18~20 帧
 *   PI_MAX=12     → 漏网 2 帧
 *   PI_MAX=10     → 漏网 **0** 帧，误杀好帧**不变**（仍 18~20）
 * 即收紧到 10 是"白捡"的：拦掉全部错帧，一个好帧都没多杀。
 *
 * 也评估并放弃了两个更重的方案：
 *   - 去趋势预处理（滑动窗口减基线）：能把伪迹帧救回一部分(1/6→4/6)，
 *     但要动 maxim 主链路(血流速度 BV / 血糖模型都吃它)，且窗口选 0.8s
 *     会把 45bpm 打成 101。收益不抵风险，且与"宁可不出数"的原则冲突。
 *   - SQI/maxim 双检测器交叉校验：误杀反而更多(22 vs 20)，漏网未清零。
 *
 * ★ 2026-07-17 已上板实测验证，结论：**PI_MAX=10 零误杀，且拦得很准**。
 * 用户反馈"测量失败太容易触发"后按上面写的方法抓了被拒帧的真实 PI 分布：
 *   - 被 motion 拦的帧 PI = **115.09% / 151.79%** —— 真伪迹，PI_MAX 就算还是 30
 *     也照样拦，即收紧到 10 并没有多杀任何帧
 *   - 所有被 low-sqi 拦的帧 PI 全部 **< 10**（2.56 / 4.07 / 4.59 / 9.01），
 *     根本没碰到 PI 闸 —— 它们是被 IBI_STD_MAX 拦的
 *   - 过闸的好帧 PI = 5.11%，与仿真预测的干净帧 3.5~4.1% 吻合
 * 误杀主因是 PPG_SQI_IBI_STD_MAX_MS，已另行放宽，见其注释。
 *
 * 教训留档：当初"收紧 PI_MAX 会让拒绝率上升"是**预测**，实测证明预测错了
 * （真伪迹的 PI 高出阈值一个数量级，10 和 30 对它们没区别）。
 * 幸好当时写死了"先看实测 PI 分布再调，不要凭感觉放宽" —— 否则这次很可能
 * 直接把 PI_MAX 放回 30，白白放行伪迹帧，而真正的病灶(IBI_STD)一动没动。
 */
#define PPG_SQI_PI_MIN          0.3f
#define PPG_SQI_PI_MAX          10.0f
/*
 * 峰间隔标准差。静息窦性心律 IBI 抖动通常 <100ms。
 *
 * ★ 200 → 350（2026-07-17 实测放宽，用户反馈"测量失败太容易触发"）
 *
 * 实测数据（一次真实测量的全部帧，见下表）说明**它才是误杀的主因**，
 * 而不是我先前收紧的 PI_MAX：
 *   状态   HR    SQI   PI        IBIstd   CV     拦它的闸
 *   done   107   100   5.11%     60ms     0.34   PASS ✓
 *   拒     67    30    151.79%   239ms    0.07   motion    ← 真伪迹
 *   拒     80    30    115.09%   236ms    0.09   motion    ← 真伪迹
 *   拒     62    70    4.59%     273ms    0.48   low-sqi   ← ★HR 合理却被拒
 *   拒     76    40    2.56%     276ms    0.52   low-sqi   ← ★HR 合理却被拒
 *   拒     86    70    9.01%     962ms    0.19   low-sqi   ← 漏检严重，该拒
 *   拒     134   70    4.07%     1022ms   0.27   low-sqi   ← 漏检严重，该拒
 *
 * 根因：SQI 用的是**自己那套时域峰检测**（sqi_find_peaks，th=正半轴均值/2），
 * 比 maxim 的差分域检测器差 —— 它漏检真峰导致 IBI_std 虚高到 273ms 甚至 962ms，
 * 但仅凭 maxim 输出的 HR 落在常见范围，不能判断它正确，也不能确认 SQI 误拒。
 *
 * 350 的取法：放行 273/276（HR 合理的好帧），仍拦 962/1022（漏检到离谱的）。
 * 不是拍脑袋 —— 好帧实测 60ms，与 273 之间本就有大 gap，350 落在 276 与 962 之间。
 *
 * 治本是让 SQI 别自己检峰、直接复用 maxim 的峰位置（两个检测器打架是设计问题），
 * 但那个改动大，赛后再做。
 */
#define PPG_SQI_IBI_STD_MAX_MS  350.0f
/*
 * 峰幅变异系数。原意是">0.5 说明脉搏波形态在 5s 内剧烈变化 = 手指在动"。
 *
 * ★ 0.5 → 0.65（2026-07-17 实测放宽）：**这个判据基本区分不了好坏**。
 * 上表实测：过闸的好帧 CV=0.34，而两个 PI 高达 115%/151% 的**真伪迹帧**
 * CV 只有 0.07/0.09（低得多！）。它跟信号质量不相关，却在扣 30 分 ——
 * IBIstd=276 那帧就是被它和 IBI 一起扣到 40 的。
 *
 * 留 0.65 当兜底（极端形态突变仍拦），但不再让它当主否决票。
 * 真正有区分度的是 DC(手指在位) 和 PI(运动伪迹)，见上面各自的实测量程。
 */
#define PPG_SQI_AMP_CV_MAX      0.65f

/*
 * 接受阈值：三项各扣 40/30/30 → 任意一项不过都低于 80 即被拒（零容忍）。
 *
 * 取 80 而非更宽松的 50/70，因为原则是"宁可不出数，也不出错数"：
 * 体检场景可以要求用户重新贴合再测，但一个错的血糖/心率进了报告无法挽回。
 * 实测 50 阈值放行了 PI=67.5%(基线漂移) 和 IBIstd=1051ms 的帧。
 */
#define PPG_SQI_ACCEPT_SCORE    80

/* ======================== 数据结构 ======================== */

typedef struct
{
    uint32_t dc;            /* IR 直流分量（原始 ADC 均值）= 手指贴合度的直接体现 */
    float   pi;             /* 灌注指数，% = AC/DC*100 */
    float   ibi_std_ms;     /* 峰间隔标准差，ms */
    float   peak_amp_cv;    /* 峰幅变异系数，无量纲 */
    int32_t n_peaks;        /* 检出峰数（<3 时统计量不可信，直接判 0 分） */
    int32_t score;          /* 综合评分 0-100 */
} ppg_sqi_t;

/* 拒绝原因，用于日志定位是哪道闸拦的 */
typedef enum
{
    PPG_GATE_PASS = 0,
    PPG_GATE_REJ_NO_FINGER, /* DC 过低，手指不在传感器上 */
    PPG_GATE_REJ_ALGO,      /* maxim 算法自己就说无效 */
    PPG_GATE_REJ_SPO2,      /* SpO2 超当前支持范围 */
    PPG_GATE_REJ_HR,        /* HR 超当前支持范围 */
    PPG_GATE_REJ_SQI,       /* SQI 评分不足（灌注差/峰幅乱，原因不单一） */
    /*
     * PI 超上限 = 低频运动伪迹主导（手指在动/没压稳）。
     *
     * 从 REJ_SQI 里单拆出来，是因为它是**唯一能给用户明确指令**的拒绝原因：
     * "手指别动" 比 "信号质量差" 可操作得多。收紧 PI_MAX 到 10 后这会
     * 成为最常见的拒绝原因，不给针对性提示的话用户只会觉得"测不出来"。
     */
    PPG_GATE_REJ_MOTION,
    PPG_GATE_REJ_SENSOR,   /* 传感器通信失败/连续样本不可用 */
    PPG_GATE_REJ_TIMEOUT,  /* 测量总时长超过上限 */
} ppg_gate_result_t;

/* ======================== API ======================== */

/**
 * @brief 从原始 IR 波形计算信号质量
 *
 * 独立实现峰检测，不复用 maxim 内部的 static 工作数组（那些是差分域的
 * 中间量，语义不同且会被下次调用覆盖）。
 *
 * @param ir   红外原始采样数组（未去直流）
 * @param len  数组长度，应为 BUFFER_SIZE(500)
 * @param fs   连续样本的采样时钟 Hz。当前 FIFO 配置为 100SPS，不能用
 *             I2C 读取耗时推算。采样间断应丢弃整窗；0或大于1000无效。
 * @param out  输出：各项质量指标 + 综合评分；入参错误时清零。
 * @return RT_EOK 成功；-RT_EINVAL 入参非法
 */
rt_err_t ppg_sqi_compute(const uint32_t *ir, int32_t len, uint32_t fs, ppg_sqi_t *out);

/**
 * @brief 综合门控判定：算法 valid + 生理范围 + SQI 三道闸
 *
 * @param sqi         ppg_sqi_compute 的结果
 * @param hr          心率 bpm
 * @param spo2        血氧 %
 * @param hr_valid    maxim 算法的心率有效标志
 * @param spo2_valid  maxim 算法的血氧有效标志
 * @return PPG_GATE_PASS 表示本帧可用于下游（标量 + 波形 IPC）
 */
ppg_gate_result_t ppg_sqi_gate(const ppg_sqi_t *sqi,
                               int32_t hr, int32_t spo2,
                               int8_t hr_valid, int8_t spo2_valid);

/** @brief 拒绝原因转可读字符串（日志用） */
const char *ppg_gate_reason_str(ppg_gate_result_t r);

#endif /* __PPG_SQI_H__ */
