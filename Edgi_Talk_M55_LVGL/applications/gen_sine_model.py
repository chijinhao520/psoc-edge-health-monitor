#!/usr/bin/env python3
"""
生成 TFLite Micro Hello World sine 模型的 C 头文件。

使用方法：
  pip install tensorflow numpy
  python gen_sine_model.py

输出：sine_model_data.h（与本脚本同目录）
"""

import numpy as np
import os

try:
    import tensorflow as tf
except ImportError:
    print("错误：需要安装 TensorFlow")
    print("  pip install tensorflow")
    raise SystemExit(1)

# ---------------------------------------------------------------
# 1. 训练一个极简 sine 模型
# ---------------------------------------------------------------
np.random.seed(42)
x_train = np.random.uniform(0, 2 * np.pi, 1000).astype(np.float32)
y_train = np.sin(x_train).astype(np.float32)

model = tf.keras.Sequential([
    tf.keras.layers.Dense(16, activation='relu', input_shape=(1,)),
    tf.keras.layers.Dense(16, activation='relu'),
    tf.keras.layers.Dense(1)
])

model.compile(optimizer='adam', loss='mse')
model.fit(x_train, y_train, epochs=500, batch_size=64, verbose=0)

# 验证
x_test = np.array([0.0, 0.5, 1.0, 1.57, 3.14], dtype=np.float32)
y_pred = model.predict(x_test.reshape(-1, 1), verbose=0).flatten()
for x, y in zip(x_test, y_pred):
    print(f"  sin({x:.2f}) ≈ {y:.4f}  (expected {np.sin(x):.4f})")

# ---------------------------------------------------------------
# 2. 转换为 TFLite 格式
# ---------------------------------------------------------------
converter = tf.lite.TFLiteConverter.from_keras_model(model)
tflite_model = converter.convert()

print(f"\n模型大小: {len(tflite_model)} bytes")

# ---------------------------------------------------------------
# 3. 导出为 C 头文件
# ---------------------------------------------------------------
output_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'sine_model_data.h')

with open(output_path, 'w') as f:
    f.write('/* Auto-generated by gen_sine_model.py — TFLite sine model */\n')
    f.write('#ifndef SINE_MODEL_DATA_H\n')
    f.write('#define SINE_MODEL_DATA_H\n\n')
    f.write(f'const unsigned int g_sine_model_data_len = {len(tflite_model)};\n\n')
    f.write('alignas(16) const unsigned char g_sine_model_data[] = {\n')

    for i, byte in enumerate(tflite_model):
        if i % 12 == 0:
            f.write('    ')
        f.write(f'0x{byte:02x},')
        if i % 12 == 11:
            f.write('\n')
        else:
            f.write(' ')

    f.write('\n};\n\n')
    f.write('#endif /* SINE_MODEL_DATA_H */\n')

print(f"已生成: {output_path}")
print("\n使用的算子: FullyConnected, ReLU (MicroMutableOpResolver 只需注册这两个)")
